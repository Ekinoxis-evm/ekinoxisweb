import { Space_Grotesk, Inter, Space_Mono } from 'next/font/google';

/** The three faces of the design system, loaded once and shared by every root layout. */
export const spaceGrotesk = Space_Grotesk({
  subsets: ['latin'],
  weight: ['300', '400', '500', '600', '700'],
  variable: '--font-space-grotesk',
  display: 'swap',
});

export const inter = Inter({
  subsets: ['latin'],
  weight: ['300', '400', '500', '600', '700'],
  variable: '--font-inter',
  display: 'swap',
});

export const spaceMono = Space_Mono({
  subsets: ['latin'],
  weight: ['400', '700'],
  variable: '--font-space-mono',
  display: 'swap',
});

export const fontClassName = `${spaceGrotesk.variable} ${inter.variable} ${spaceMono.variable}`;
